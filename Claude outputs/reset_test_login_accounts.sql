-- التنفيذ: مسح حسابات تسجيل الدخول (auth.users) لكل حد عنده باسورد حاليًا،
-- ما عدا أمناء الخدمة العامة التلاتة (ADM01/ADM02/ADM03). بما إن عمود
-- auth_user_id في جدول public.users متعرّف بـ "ON DELETE SET NULL"، مجرد
-- ما الحساب يتمسح من هنا، عمود auth_user_id بتاعه في public.users بيرجع
-- NULL تلقائيًا — يعني الكود بتاعه (username) يرجع "مفيهوش باسورد" فورًا،
-- من غير أي خطوة تانية.
DELETE FROM auth.users
WHERE id IN (
  SELECT auth_user_id FROM public.users
  WHERE role <> 'super_admin'
    AND (username IS NULL OR username NOT IN ('ADM01', 'ADM02', 'ADM03'))
    AND auth_user_id IS NOT NULL
);

